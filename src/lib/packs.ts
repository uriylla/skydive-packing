import { and, asc, count, desc, eq, or, sql } from "drizzle-orm";
import type { PostgresJsDatabase } from "drizzle-orm/postgres-js";
import * as schema from "@/db/schema";
import { operatingDays, packs, parachutes, users } from "@/db/schema";
import { dayKey } from "./time";

export type Db = PostgresJsDatabase<typeof schema>;

/** How far back a queued (offline) pack may be dated by the device. */
const MAX_BACKDATE_MS = 48 * 60 * 60 * 1000;
/** Tolerance for device clocks running slightly ahead. */
const MAX_FUTURE_MS = 2 * 60 * 1000;

export type RegisterPackInput = {
  /** UUID generated by the device; makes retries idempotent. */
  clientId: string;
  packerId: number;
  /** As typed or scanned, e.g. "23" or "023". */
  parachuteNumber: string;
  /** When the pack was registered on the device (matters for queued retries). */
  packedAt?: Date;
  /** Device the pack came from. */
  stationId?: number;
};

export type RegisteredPack = {
  id: number;
  clientId: string;
  packedAt: string;
  packerName: string;
  parachuteNumber: string;
};

export type RegisterPackError =
  | "PACKER_NOT_FOUND"
  | "PACKER_INACTIVE"
  | "PARACHUTE_NOT_FOUND"
  | "PARACHUTE_AMBIGUOUS"
  | "PARACHUTE_RETIRED"
  | "PARACHUTE_OUT_OF_SERVICE";

export type RegisterPackResult =
  | { ok: true; pack: RegisteredPack; duplicate: boolean }
  | { ok: false; error: RegisterPackError; message: string };

const fail = (error: RegisterPackError, message: string): RegisterPackResult => ({
  ok: false,
  error,
  message,
});

/** Lowercase and strip leading zeros, so "23", "023" and "0023" all match. */
export function normalizeNumber(n: string): string {
  const s = n.trim().toLowerCase();
  const stripped = s.replace(/^0+/, "");
  return stripped === "" && s !== "" ? "0" : stripped;
}

/** Pick a time to store: the device's if plausible, otherwise the server's. */
export function resolvePackedAt(deviceTime: Date | undefined, now: Date): Date {
  if (!deviceTime || Number.isNaN(deviceTime.getTime())) return now;
  const diff = now.getTime() - deviceTime.getTime();
  if (diff > MAX_BACKDATE_MS || diff < -MAX_FUTURE_MS) return now;
  return deviceTime;
}

export async function findParachute(db: Db, input: string) {
  const raw = input.trim().toLowerCase();
  const norm = normalizeNumber(input);
  if (!raw) return { match: null, ambiguous: false };

  const normalizedCol = sql`coalesce(nullif(ltrim(lower(${parachutes.number}), '0'), ''), '0')`;
  const rows = await db
    .select()
    .from(parachutes)
    .where(or(sql`lower(${parachutes.number}) = ${raw}`, sql`${normalizedCol} = ${norm}`))
    .limit(5);

  const exact = rows.find((r) => r.number.toLowerCase() === raw);
  if (exact) return { match: exact, ambiguous: false };
  if (rows.length === 1) return { match: rows[0], ambiguous: false };
  return { match: null, ambiguous: rows.length > 1 };
}

/** Get or create the jornada for a calendar date. */
export async function ensureOperatingDay(db: Db, date: string): Promise<number> {
  const [row] = await db
    .insert(operatingDays)
    .values({ date })
    .onConflictDoUpdate({ target: operatingDays.date, set: { date } })
    .returning({ id: operatingDays.id });
  return row.id;
}

async function loadPack(db: Db, clientId: string): Promise<RegisteredPack | null> {
  const [row] = await db
    .select({
      id: packs.id,
      clientId: packs.clientId,
      packedAt: packs.packedAt,
      packerName: users.name,
      parachuteNumber: parachutes.number,
    })
    .from(packs)
    .innerJoin(users, eq(users.id, packs.packerId))
    .innerJoin(parachutes, eq(parachutes.id, packs.parachuteId))
    .where(eq(packs.clientId, clientId));
  return row ? { ...row, packedAt: row.packedAt.toISOString() } : null;
}

export async function registerPack(
  db: Db,
  input: RegisterPackInput,
  now: Date = new Date(),
): Promise<RegisterPackResult> {
  // A retry of a pack that already reached the server: return it as-is.
  const existing = await loadPack(db, input.clientId);
  if (existing) return { ok: true, pack: existing, duplicate: true };

  const [packer] = await db.select().from(users).where(eq(users.id, input.packerId));
  if (!packer) return fail("PACKER_NOT_FOUND", "Plegador no encontrado.");
  if (!packer.active) return fail("PACKER_INACTIVE", `${packer.name} está desactivado.`);

  const { match: chute, ambiguous } = await findParachute(db, input.parachuteNumber);
  if (ambiguous) {
    return fail(
      "PARACHUTE_AMBIGUOUS",
      `Hay varios paracaídas que coinciden con "${input.parachuteNumber}". Escribe el número completo.`,
    );
  }
  if (!chute) {
    return fail("PARACHUTE_NOT_FOUND", `No existe el paracaídas "${input.parachuteNumber}".`);
  }
  if (chute.retired) {
    return fail("PARACHUTE_RETIRED", `El paracaídas ${chute.number} está dado de baja.`);
  }
  if (chute.status === "out_of_service") {
    return fail(
      "PARACHUTE_OUT_OF_SERVICE",
      `El paracaídas ${chute.number} está fuera de servicio.`,
    );
  }

  const packedAt = resolvePackedAt(input.packedAt, now);
  const dayId = await ensureOperatingDay(db, dayKey(packedAt));

  await db
    .insert(packs)
    .values({
      clientId: input.clientId,
      packerId: packer.id,
      parachuteId: chute.id,
      dayId,
      packedAt,
      stationId: input.stationId,
    })
    .onConflictDoNothing({ target: packs.clientId });

  const pack = await loadPack(db, input.clientId);
  if (!pack) throw new Error("Pack insert failed");
  return { ok: true, pack, duplicate: false };
}

export type DaySummary = {
  date: string;
  total: number;
  byPacker: { packerId: number; name: string; count: number }[];
  recent: { id: number; packedAt: string; packerName: string; parachuteNumber: string }[];
};

/** Totals and latest packs for one jornada (voided packs excluded). */
export async function getDaySummary(db: Db, date: string, recentLimit = 10): Promise<DaySummary> {
  const live = and(eq(operatingDays.date, date), eq(packs.voided, false));

  const byPacker = await db
    .select({ packerId: users.id, name: users.name, count: count() })
    .from(packs)
    .innerJoin(operatingDays, eq(operatingDays.id, packs.dayId))
    .innerJoin(users, eq(users.id, packs.packerId))
    .where(live)
    .groupBy(users.id, users.name)
    .orderBy(desc(count()), asc(users.name));

  const recent = await db
    .select({
      id: packs.id,
      packedAt: packs.packedAt,
      packerName: users.name,
      parachuteNumber: parachutes.number,
    })
    .from(packs)
    .innerJoin(operatingDays, eq(operatingDays.id, packs.dayId))
    .innerJoin(users, eq(users.id, packs.packerId))
    .innerJoin(parachutes, eq(parachutes.id, packs.parachuteId))
    .where(live)
    .orderBy(desc(packs.packedAt), desc(packs.id))
    .limit(recentLimit);

  return {
    date,
    total: byPacker.reduce((sum, p) => sum + p.count, 0),
    byPacker,
    recent: recent.map((r) => ({ ...r, packedAt: r.packedAt.toISOString() })),
  };
}

/** Data the packing station needs: who can pack, and which parachutes exist. */
export async function getStationData(db: Db) {
  const [packers, chutes] = await Promise.all([
    db
      .select({ id: users.id, name: users.name })
      .from(users)
      .where(eq(users.active, true))
      .orderBy(asc(users.name)),
    db
      .select({ number: parachutes.number, status: parachutes.status })
      .from(parachutes)
      .where(eq(parachutes.retired, false))
      .orderBy(asc(parachutes.number)),
  ]);
  return { packers, parachutes: chutes };
}
